class Assignment {
    public static void main(String[] args) {

        // The Assignment oprator  symbol is "=" equal to 
        int Myint = 7;  // Here 7 is assigning to the Myint 
        System.out.println(Myint);

        char Letter = 'K';  // Here "K" is assign to the Letter Character should be in the Single qoute
        System.out.println(Letter);

        String Name = "Kedar"; // Here "Kedar" Assign to the Name variable
        System.out.println(Name);

    }
    
}
